export function ContextHelp({
  section,
  onClose,
  onOverview,
  invoices,
  notify,
}: {
  section: string;
  onClose: () => void;
  onOverview: () => void;
  invoices: Invoice[];
  notify: (message: string, error?: boolean) => void;
}) {
  const [training, setTraining] = useState(false);
  const { invoiceId } = useWorkContext();
  const [title, steps] = help[section] || help.workflow;
  return (
    <Dialog title={training ? 'Демонстрация разговора' : title} onClose={onClose} wide>
      <ol className="context-help-steps">
        {steps.map((step) => (
          <li key={step}>{step}</li>
        ))}
      </ol>
      <p>
        Закройте подсказку, чтобы продолжить с того же места. Общий обзор доступен по кнопке
        «Обучение».
      </p>
      <button type="button" className="button button-outline" onClick={onOverview}>
        Показать обзор раздела
      </button>
      <button
        type="button"
        className="button button-outline"
        onClick={() => setTraining(!training)}
      >
        {training ? 'Свернуть демонстрацию' : 'Учебный разговор'}
      </button>
      {training && (
        <YandexDesk
          mode="voice"
          invoices={invoices}
          notify={notify}
          invoiceId={invoiceId || undefined}
        />
      )}
      {section === 'service' && <SupportContact />}
    </Dialog>
  );
}
